import { sqliteTable as table } from "drizzle-orm/sqlite-core"
import { c } from "@lovrozagar/comb/sqlite/columns"
import * as z from "zod"
export const docSchema = z.object({ a: z.string() })
export const peer = table("peer", { id: c.id("peer") })
export const row = table("row", {
	id: c.id("row"),
	t: c.text("t"),
	tNN: c.text("tNN").notNull(),
	tDef: c.text("tDef").notNull().default("x"),
	tMax: c.text("tMax", { min: 2, max: 5 }),
	tTrim: c.text("tTrim", { trim: true, lowercase: true, max: 4 }).notNull(),
	tUp: c.text("tUp", { uppercase: true }),
	tPat: c.text("tPat", { pattern: "/^[a-z]+$/" }),
	email: c.text("email", { email: true }).notNull(),
	emailMax: c.text("emailMax", { email: true, max: 20, pattern: "/@corp\\.com$/" }),
	url: c.text("url", { url: true }),
	img: c.text("img", { imageUri: true }),
	nm: c.text("nm", { name: true }),
	pw: c.text("pw", { password: true }).notNull(),
	priv: c.text("priv", { private: true }),
	_under: c.text("_under"),
	nomut: c.text("nomut", { nomutate: true }),
	auto: c.text("auto", { autogenerate: true }),
	other: c.ref("other"),
	otherNN: c.ref("otherNN").notNull(),
	otherMutId: c.ref("otherMutId", { mutable: true }).references(() => peer.id),
	tenantId: c.ref("tenantId", { tenant: true }).notNull().references(() => peer.id),
	en: c.enum("en", ["a", "b"] as const).notNull(),
	enS: c.enum("enS", ["new", "done"] as const, { initial: "new", terminal: ["done"], transitions: { new: ["done"] } }).notNull().default("new"),
	enNull: c.enum("enNull", ["a"] as const),
	i: c.integer("i"),
	iB: c.integer("iB", { min: 0, max: 10 }).notNull(),
	iFrac: c.integer("iFrac", { min: 0.5, max: 9.5 }),
	iDef: c.integer("iDef").notNull().default(0),
	r: c.real("r"),
	rB: c.real("rB", { min: -1.5, max: 1.5 }).notNull(),
	b: c.boolean("b"),
	bNN: c.boolean("bNN").notNull().default(false),
	ts: c.timestamp("ts"),
	tsB: c.timestamp("tsB", { min: 0 }).notNull(),
	j: c.json("j", docSchema),
	jNN: c.json("jNN", docSchema, { maxBytes: 100 }).notNull(),
	createdAt: c.createdAt("createdAt"),
	updatedAt: c.updatedAt("updatedAt"),
	deletedAt: c.deletedAt("deletedAt"),
})
