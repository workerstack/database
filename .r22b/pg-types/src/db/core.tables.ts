import * as p from "drizzle-orm/pg-core"
import { c } from "@lovrozagar/comb/pg/columns"
export const row = p.pgTable("row", {
	id: c.id("row"),
	vc: p.varchar({ length: 4 }),
	ch: p.char({ length: 4 }),
	uuid: p.uuid(),
	date: p.date({ mode: "string" }),
	ts: p.timestamp({ mode: "string" }),
	ts3: p.timestamp({ mode: "string", precision: 3 }),
	tstz: p.timestamp({ mode: "string", withTimezone: true }),
	tstz3: p.timestamp({ mode: "string", withTimezone: true, precision: 3 }),
	time: p.time(),
	timetz: p.time({ withTimezone: true }),
	timetz3: p.time({ withTimezone: true, precision: 3 }),
	iv: p.interval(),
	ivd: p.interval({ fields: "day" }),
	num52: p.numeric({ precision: 5, scale: 2 }),
	num5: p.numeric({ precision: 5 }),
	num: p.numeric(),
	numN: p.numeric({ mode: "number", precision: 5, scale: 2 }),
	numNbare: p.numeric({ mode: "number" }),
	bigS: p.bigint({ mode: "string" }),
	bigN: p.bigint({ mode: "number" }),
	int: p.integer(),
	small: p.smallint(),
	real: p.real(),
	dbl: p.doublePrecision(),
	inet: p.inet(),
	cidr: p.cidr(),
	mac: p.macaddr(),
	mac8: p.macaddr8(),
	bit: p.bit({ dimensions: 3 }),
	txt: p.text(),
	jsb: p.jsonb(),
	js: p.json(),
	bool: p.boolean(),
})
