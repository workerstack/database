import { pgTable as table, varchar, char, uuid, date, inet, cidr, numeric, real, doublePrecision, bigint, smallint, integer, jsonb, json, text, pgEnum, timestamp, time, interval, macaddr, macaddr8, bit, boolean } from "drizzle-orm/pg-core"
import { c } from "@lovrozagar/comb/pg/columns"
import * as z from "zod"
export const docSchema = z.object({ a: z.string() }).meta({ id: "Doc" })
export const sSchema = z.object({ s: z.string() })
export const listSchema = z.array(z.string())
export const mood = pgEnum("mood", ["sad", "ok"])
export const parent = table("parent", { id: c.id("par") })
export const row = table("row", {
	id: c.id("row"),
	parent_id: c.ref("parent_id").references(() => parent.id),
	t_plain: c.text("t_plain"),
	t_req: c.text("t_req").notNull(),
	t_bounds: c.text("t_bounds", { min: 2, max: 5 }).notNull(),
	t_pat_dot: c.text("t_pat_dot", { pattern: "/^[^\n\r]{2}$/" }),
	t_pat_p: c.text("t_pat_p", { pattern: "/^\\p{L}+$/" }),
	t_trim: c.text("t_trim", { trim: true, min: 1, max: 4 }),
	t_email: c.text("t_email", { email: true }).notNull(),
	t_url: c.text("t_url", { url: true }),
	t_name: c.text("t_name", { name: true, max: 20 }),
	e: c.enum("e", ["a", "b"]).notNull().default("a"),
	i: c.integer("i", { min: 0, max: 10 }),
	r: c.real("r", { min: 0.5, max: 9.5 }),
	ts: c.timestamp("ts"),
	j: c.json("j", docSchema),
	jb: c.json("jb", sSchema, { maxBytes: 20 }).notNull(),
	p_varchar: varchar("p_varchar", { length: 5 }),
	p_char: char("p_char", { length: 3 }),
	p_uuid: uuid("p_uuid"),
	p_date: date("p_date"),
	p_ts: timestamp("p_ts", { mode: "string" }),
	p_tstz: timestamp("p_tstz", { mode: "string", withTimezone: true }),
	p_time: time("p_time"),
	p_timetz: time("p_timetz", { withTimezone: true }),
	p_interval: interval("p_interval"),
	p_inet: inet("p_inet"),
	p_cidr: cidr("p_cidr"),
	p_mac: macaddr("p_mac"),
	p_mac8: macaddr8("p_mac8"),
	p_bit: bit("p_bit", { dimensions: 4 }),
	p_num: numeric("p_num", { precision: 5, scale: 2 }),
	p_num_free: numeric("p_num_free"),
	p_num_n: numeric("p_num_n", { precision: 5, scale: 2, mode: "number" }),
	p_real: real("p_real"),
	p_double: doublePrecision("p_double"),
	p_big_n: bigint("p_big_n", { mode: "number" }),
	p_big_s: bigint("p_big_s", { mode: "string" }),
	p_small: smallint("p_small"),
	p_int: integer("p_int"),
	p_jsonb: jsonb("p_jsonb").notNull(),
	p_json: json("p_json"),
	p_bool: boolean("p_bool"),
	p_mood: mood("p_mood"),
	p_arr: text("p_arr").array(),
	p_arr2: integer("p_arr2").array("[][]"),
	created_at: c.createdAt("created_at"),
	updated_at: c.updatedAt("updated_at"),
	deleted_at: c.deletedAt("deleted_at"),
})
